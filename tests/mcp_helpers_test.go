// pkcePair returns a fresh RFC 7636 code verifier and its S256 challenge.
func pkcePair(t *testing.T) (verifier string, challenge string) {
	t.Helper()

	raw := make([]byte, 32)
	_, err := rand.Read(raw)
	require.NoError(t, err)

	verifier = base64.RawURLEncoding.EncodeToString(raw)
	sum := sha256.Sum256([]byte(verifier))

	return verifier, base64.RawURLEncoding.EncodeToString(sum[:])
}

// noRedirectClient returns an HTTP client that surfaces redirects instead of
