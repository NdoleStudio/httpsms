// completeFirebaseConsent posts the consent form (transaction, Firebase ID
// token, approved scopes) and returns the Location header of the resulting
// redirect. expectedStatus lets a caller assert a rejected consent instead.
func completeFirebaseConsent(t *testing.T, transactionID, idToken string, approvedScopes []string, expectedStatus int) string {
	t.Helper()

	form := url.Values{
		"transaction_id": {transactionID},
		"id_token":       {idToken},
	}
	form["approved_scopes"] = approvedScopes

	response, body := doMCPRequest(
		t,
		http.MethodPost,
		mcpBaseURL+"/oauth/firebase/complete",
		"application/x-www-form-urlencoded",
		strings.NewReader(form.Encode()),
	)
	require.Equal(
		t,
		expectedStatus,
		response.StatusCode,
		"firebase complete: %s\n(an unexpected 401 usually means WireMock is serving a certificate that no longer matches "+
			"%s: re-run `bash generate-firebase-credentials.sh` and `docker compose up -d --force-recreate wiremock mcp`)",
		redactSecrets(body),
		mcpSigningKeyPath,
	)

	return response.Header.Get("Location")
}

