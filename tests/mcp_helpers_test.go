// transactionIDPattern extracts the authorization transaction ID from the
// rendered consent page. The tests drive the consent form exactly as the
// browser would: they never reach into the MCP service's Redis state.
var transactionIDPattern = regexp.MustCompile(`name="transaction_id" value="([^"]+)"`)

// secretFieldPattern matches every JSON field an httpSMS or OAuth response
// carries a live secret in. redactSecrets replaces their values so a failing
// assertion's message can quote a response body without printing a usable
// access token, refresh token, or API key into the test log.
var secretFieldPattern = regexp.MustCompile(`"(access_token|refresh_token|id_token|api_key|client_secret|registration_access_token)"\s*:\s*"[^"]*"`)

// redactSecrets returns body with every secret field value replaced. Every
// failure message that quotes a token-endpoint, user, or API-key response
// body must pass it through this function first.
func redactSecrets(body string) string {
	return secretFieldPattern.ReplaceAllString(body, `"$1":"[redacted]"`)
}

// assertSecretNotLogged asserts secret never appears in logs, without ever
// writing either the secret or the surrounding log lines into the test output
// (testify's NotContains would print both on failure). description names the
// secret in the failure message instead.
func assertSecretNotLogged(t *testing.T, logs, secret, description string) {
	t.Helper()
	require.NotEmpty(t, secret, "refusing to search the logs for an empty %s", description)
	assert.False(t, strings.Contains(logs, secret), "%s must never appear in the MCP service logs", description)
}

// signingKeyOnce loads the generated RSA signing key at most once per test
// binary: every test that mints a Firebase ID token or an API delegation
// token shares it.
var (
	signingKeyOnce sync.Once
	signingKey     *rsa.PrivateKey
	signingKeyErr  error
)

// tokenResponse is the RFC 6749 token endpoint success body.
type tokenResponse struct {
	AccessToken  string `json:"access_token"`
	TokenType    string `json:"token_type"`
	ExpiresIn    int64  `json:"expires_in"`
	RefreshToken string `json:"refresh_token"`
	Scope        string `json:"scope"`
}

// oauthErrorResponse is the RFC 6749 Section 5.2 error body every direct
// (non-redirect) OAuth error carries.
type oauthErrorResponse struct {
	Error            string `json:"error"`
	ErrorDescription string `json:"error_description"`
}

// mcpSigningKey returns the RSA private key the MCP container signs with and
// the tests sign test Firebase ID tokens and API delegation tokens with.
func mcpSigningKey(t *testing.T) *rsa.PrivateKey {
	t.Helper()

	signingKeyOnce.Do(func() {
		contents, err := os.ReadFile(mcpSigningKeyPath)
		if err != nil {
			signingKeyErr = fmt.Errorf("read %s: %w", mcpSigningKeyPath, err)
			return
		}

		block, _ := pem.Decode(contents)
		if block == nil {
			signingKeyErr = fmt.Errorf("%s does not contain a PEM block", mcpSigningKeyPath)
			return
		}

		if key, err := x509.ParsePKCS1PrivateKey(block.Bytes); err == nil {
			signingKey = key
			return
		}

		parsed, err := x509.ParsePKCS8PrivateKey(block.Bytes)
		if err != nil {
			signingKeyErr = fmt.Errorf("parse %s: %w", mcpSigningKeyPath, err)
			return
		}

		key, ok := parsed.(*rsa.PrivateKey)
		if !ok {
			signingKeyErr = fmt.Errorf("%s is a %T, not an RSA private key", mcpSigningKeyPath, parsed)
			return
		}
		signingKey = key
	})

	require.NoError(t, signingKeyErr, "run `bash generate-firebase-credentials.sh` before the MCP integration tests")
	require.NotNil(t, signingKey)

	return signingKey
}

// signFirebaseTestToken mints a Firebase-style ID token for userID that the
// MCP service verifies against the WireMock-served certificate for
// mcpSigningKeyID. It is the deterministic, offline stand-in for a real
// browser Firebase sign-in.
func signFirebaseTestToken(t *testing.T, userID, email string) string {
	t.Helper()

	now := time.Now().UTC()
	claims := jwt.MapClaims{
		"iss":       firebaseIssuer,
		"aud":       firebaseProjectID,
		"sub":       userID,
		"user_id":   userID,
		"email":     email,
		"auth_time": now.Add(-time.Minute).Unix(),
		"iat":       now.Add(-time.Minute).Unix(),
		"exp":       now.Add(time.Hour).Unix(),
	}

	token := jwt.NewWithClaims(jwt.SigningMethodRS256, claims)
	token.Header["kid"] = mcpSigningKeyID

	signed, err := token.SignedString(mcpSigningKey(t))
	require.NoError(t, err)

	return signed
}

// signAPIDelegationToken mints a downstream API delegation token exactly as
// the MCP service's tool handlers do: issued by the MCP service, audienced to
// the httpSMS API, and bound to one HTTP method and path.
//
// It exists so the tests can prove the API's own delegated-token verifier
// enforces that binding, without going through a tool that can only ever mint
// a correctly bound token.
func signAPIDelegationToken(t *testing.T, userID string, scopes []string, method, path string, options ...func(jwt.MapClaims)) string {
	t.Helper()

	now := time.Now().UTC()
	claims := jwt.MapClaims{
		"iss":         mcpBaseURL,
		"aud":         mcpAPIAudience,
		"sub":         userID,
		"scopes":      scopes,
		"http_method": method,
		"http_path":   path,
		"iat":         now.Unix(),
		"nbf":         now.Unix(),
		"exp":         now.Add(2 * time.Minute).Unix(),
		"jti":         uuid.NewString(),
	}
	for _, option := range options {
		option(claims)
	}

	token := jwt.NewWithClaims(jwt.SigningMethodRS256, claims)
	token.Header["kid"] = mcpSigningKeyID

	signed, err := token.SignedString(mcpSigningKey(t))
	require.NoError(t, err)

	return signed
}

