// completeOAuthCodeFlowAs runs the complete PKCE authorization-code flow for
// an arbitrary Firebase UID and returns the issued tokens.
func completeOAuthCodeFlowAs(t *testing.T, userID, email string, scopes []string) tokenResponse {
	t.Helper()

	params := requestAuthorizationCode(t, userID, email, scopes)

	response, body := redeemAuthorizationCode(t, params)
	require.Equal(t, http.StatusOK, response.StatusCode, "token: %s", redactSecrets(body))

	var tokens tokenResponse
	require.NoError(t, json.Unmarshal([]byte(body), &tokens))
	require.NotEmpty(t, tokens.AccessToken)
	require.NotEmpty(t, tokens.RefreshToken)
	require.Equal(t, "Bearer", tokens.TokenType)

	return tokens
}

// bearerTransport attaches a fixed bearer token to every request.
type bearerTransport struct {
	token string
	next  http.RoundTripper
}

func (t *bearerTransport) RoundTrip(request *http.Request) (*http.Response, error) {
	cloned := request.Clone(request.Context())
	cloned.Header.Set("Authorization", "Bearer "+t.token)

	next := t.next
	if next == nil {
		next = http.DefaultTransport
	}
	return next.RoundTrip(cloned)
}

// newMCPClient connects the official MCP Go SDK client to the running MCP
// service over authenticated Streamable HTTP and returns the live session.
//
// protocolVersion must be mcpProtocolLatest: the SDK client always negotiates
// the newest protocol version it supports and offers no exported knob to
// downgrade it. Compatibility with mcpProtocolPrevious is covered by
// callLegacyMCP, which speaks the wire protocol directly and is therefore the
// only way to assert a legacy initialize handshake at all.
func newMCPClient(t *testing.T, accessToken, protocolVersion string, options ...func(*mcp.ClientOptions)) *mcp.ClientSession {
	t.Helper()
	require.Equal(t, mcpProtocolLatest, protocolVersion, "the SDK client only negotiates %s; use callLegacyMCP for %s", mcpProtocolLatest, mcpProtocolPrevious)

	clientOptions := &mcp.ClientOptions{}
	for _, option := range options {
		option(clientOptions)
	}

	client := mcp.NewClient(&mcp.Implementation{Name: "httpsms-integration-tests", Version: "test"}, clientOptions)

	transport := &mcp.StreamableClientTransport{
		Endpoint: mcpEndpointURL,
		HTTPClient: &http.Client{
			Timeout:   60 * time.Second,
			Transport: &bearerTransport{token: accessToken},
		},
		// The MCP service is stateless and never initiates a request of its
		// own, so a standalone SSE stream would only add a connection to
		// tear down.
		DisableStandaloneSSE: true,
	}

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()

	session, err := client.Connect(ctx, transport, nil)
	require.NoError(t, err)
	t.Cleanup(func() { _ = session.Close() })

	return session
}

// callMCPTool calls name with arguments and fails the test on a protocol-level
// error. A tool-level error (CallToolResult.IsError) is returned to the
// caller, which is what every "this call must be refused" assertion inspects.
func callMCPTool(t *testing.T, session *mcp.ClientSession, name string, arguments any) *mcp.CallToolResult {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()

	result, err := session.CallTool(ctx, &mcp.CallToolParams{Name: name, Arguments: arguments})
	require.NoError(t, err, "tool %s", name)
	require.NotNil(t, result)

	return result
}

// toolResultText concatenates every text content block of result, which is
// where a tool-level error message is carried.
func toolResultText(result *mcp.CallToolResult) string {
	var builder strings.Builder
	for _, content := range result.Content {
		if text, ok := content.(*mcp.TextContent); ok {
			builder.WriteString(text.Text)
		}
	}
	return builder.String()
}

// decodeToolOutput decodes a successful tool call's structured output into out.
func decodeToolOutput(t *testing.T, result *mcp.CallToolResult, out any) {
	t.Helper()
	require.False(t, result.IsError, "tool call failed: %s", toolResultText(result))
	require.NotNil(t, result.StructuredContent, "tool call returned no structured content")

	encoded, err := json.Marshal(result.StructuredContent)
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(encoded, out))
}

// jsonRPCResponse is a decoded JSON-RPC response from the MCP endpoint, used
// by the raw-protocol helpers below.
type jsonRPCResponse struct {
	JSONRPC string          `json:"jsonrpc"`
	ID      any             `json:"id"`
	Result  json.RawMessage `json:"result"`
	Error   *struct {
		Code    int             `json:"code"`
		Message string          `json:"message"`
		Data    json.RawMessage `json:"data"`
	} `json:"error"`
}

// callLegacyMCP sends a single JSON-RPC request to the MCP endpoint over raw
// Streamable HTTP, announcing protocolVersion. It is how the suite exercises
// the 2025-11-25 protocol, which the SDK client cannot be asked to negotiate.
func callLegacyMCP(t *testing.T, accessToken, protocolVersion, method string, params any) (*http.Response, jsonRPCResponse) {
	t.Helper()

	payload := map[string]any{
		"jsonrpc": "2.0",
		"id":      uuid.NewString(),
		"method":  method,
	}
	if params != nil {
		payload["params"] = params
	}

	body, err := json.Marshal(payload)
	require.NoError(t, err)

	request, err := http.NewRequest(http.MethodPost, mcpEndpointURL, strings.NewReader(string(body)))
	require.NoError(t, err)
	request.Header.Set("Content-Type", "application/json")
	request.Header.Set("Accept", "application/json, text/event-stream")
	if accessToken != "" {
		request.Header.Set("Authorization", "Bearer "+accessToken)
	}
	if protocolVersion != "" && method != "initialize" {
		request.Header.Set("Mcp-Protocol-Version", protocolVersion)
	}

	response, err := noRedirectClient().Do(request)
	require.NoError(t, err)
	defer func() { _ = response.Body.Close() }()

	raw, err := io.ReadAll(response.Body)
	require.NoError(t, err)

	var decoded jsonRPCResponse
	if len(raw) > 0 && response.StatusCode < http.StatusBadRequest {
		require.NoError(t, json.Unmarshal(raw, &decoded), "response body: %s", string(raw))
	}

	return response, decoded
}

