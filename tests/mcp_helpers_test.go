// pollMessageStatusAs polls GET /v1/messages/{id} with apiKey until the
// message reaches targetStatus, mirroring pollMessageStatus for a user other
// than the shared integration-test user.
func pollMessageStatusAs(ctx context.Context, t *testing.T, apiKey, messageID, targetStatus string, timeout time.Duration) {
	t.Helper()

	deadline := time.Now().Add(timeout)
	lastStatus := ""
	for time.Now().Before(deadline) {
		request, err := http.NewRequestWithContext(ctx, http.MethodGet, apiBaseURL+"/v1/messages/"+messageID, nil)
		require.NoError(t, err)
		request.Header.Set("x-api-key", apiKey)

		response, err := http.DefaultClient.Do(request)
		require.NoError(t, err)
		body, err := io.ReadAll(response.Body)
		_ = response.Body.Close()
		require.NoError(t, err)

		if response.StatusCode == http.StatusOK {
			var decoded struct {
				Data struct {
					Status string `json:"status"`
				} `json:"data"`
			}
			if json.Unmarshal(body, &decoded) == nil {
				lastStatus = decoded.Data.Status
				if lastStatus == targetStatus {
					return
				}
			}
		}

		time.Sleep(500 * time.Millisecond)
	}

	t.Fatalf("message %s did not reach status %q within %v (last status %q)", messageID, targetStatus, timeout, lastStatus)
}

// mcpContainerLogs returns the MCP container's logs, or ok == false when the
// Docker CLI is unavailable (the log-redaction assertion is then skipped
// rather than failing for an unrelated reason).
func mcpContainerLogs(t *testing.T) (string, bool) {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()

	command := exec.CommandContext(ctx, "docker", "compose", "logs", "--no-color", "mcp")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Logf("cannot read MCP container logs (%v); skipping the log redaction assertion", err)
		return "", false
	}

	return string(output), true
}

// resetStackInstruction is the exact recovery procedure for a stack whose
// immutable seeded prerequisites are missing or stale. It is only ever
// printed when a prerequisite really is invalid: a routine repeated run
// against a healthy stack never needs it, because no test mutates anything
// the preflight checks.
const resetStackInstruction = "reset the stack and re-seed it:\n" +
	"    cd tests\n" +
	"    docker compose down -v\n" +
	"    docker compose up -d --build --wait mcp\n" +
	"    docker compose up -d seed && docker compose wait seed"

var (
	mcpPreflightOnce sync.Once
	mcpPreflightErr  error
)

// requireMCPStack runs the (fast, once-per-binary) preflight every MCP test
// starts with: the generated signing key exists, the API and MCP services
// answer their health checks, and every immutable seeded prerequisite is
// present. It fails with the exact command to run rather than letting a
// missing prerequisite surface later as an unrelated assertion failure.
func requireMCPStack(t *testing.T) {
	t.Helper()

	mcpPreflightOnce.Do(func() { mcpPreflightErr = mcpPreflight() })
	if mcpPreflightErr != nil {
		t.Fatalf("MCP integration preflight failed: %v", mcpPreflightErr)
	}
}

// mcpPreflight validates every prerequisite the MCP suite cannot run without.
// It deliberately checks only immutable state: the rotation user's primary
// API key is never checked, because rotating it is exactly what the rotation
// tests do, and requiring its seeded value to still be current is what made
// the suite non-re-runnable in the first place.
func mcpPreflight() error {
	if _, err := os.Stat(mcpSigningKeyPath); err != nil {
		return fmt.Errorf("%s is missing: run `bash generate-firebase-credentials.sh` in tests/ (%w)", mcpSigningKeyPath, err)
	}

	client := &http.Client{Timeout: 10 * time.Second}
	services := []struct{ name, url string }{
		{"the httpSMS API", apiBaseURL + "/health"},
		{"the MCP service", mcpBaseURL + "/health"},
	}
	for _, service := range services {
		if err := preflightStatusOK(client, service.url, ""); err != nil {
			return fmt.Errorf("%s is not reachable: %w\nstart the stack with `docker compose up -d --build --wait mcp` in tests/", service.name, err)
		}
	}

	seededUsers := []struct{ name, apiKey string }{
		{"the MCP test user (" + mcpTestUserID + ")", mcpTestUserAPIKey},
		{"the isolated user (" + mcpIsolatedUserID + ")", mcpIsolatedUserKey},
	}
	for _, user := range seededUsers {
		if err := preflightStatusOK(client, apiBaseURL+"/v1/users/me", user.apiKey); err != nil {
			return fmt.Errorf("the seeded primary API key of %s is not valid: %w\nno test ever rotates it, so %s", user.name, err, resetStackInstruction)
		}
	}

	if err := preflightContains(
		client,
		apiBaseURL+"/v1/phones?skip=0&limit=5&query="+url.QueryEscape(mcpSeededPhoneQuery),
		mcpTestUserAPIKey,
		mcpSeededPhoneNumber,
	); err != nil {
		return fmt.Errorf("the seeded MCP phone %s is missing: %w\n%s", mcpSeededPhoneNumber, err, resetStackInstruction)
	}

	if err := preflightContains(
		client,
		apiBaseURL+"/v1/message-threads?skip=0&limit=5&owner="+url.QueryEscape(mcpSeededPhoneNumber),
		mcpTestUserAPIKey,
		mcpSeededThreadContact,
	); err != nil {
		return fmt.Errorf("the seeded MCP message thread %s -> %s is missing: %w\n%s", mcpSeededPhoneNumber, mcpSeededThreadContact, err, resetStackInstruction)
	}

	return nil
}

// preflightStatusOK performs a single GET and requires a 200. apiKey may be
// empty for an unauthenticated health endpoint. The response body is never
// included in the error: /v1/users/me carries the user's primary API key.
func preflightStatusOK(client *http.Client, requestURL, apiKey string) error {
	status, _, err := preflightGet(client, requestURL, apiKey)
	if err != nil {
		return err
	}
	if status != http.StatusOK {
		return fmt.Errorf("GET %s returned %d", requestURL, status)
	}
	return nil
}

// preflightContains performs a single authenticated GET and requires the
// response to contain expected. Only expected -- never the response body,
// which may carry secrets -- appears in the error.
func preflightContains(client *http.Client, requestURL, apiKey, expected string) error {
	status, body, err := preflightGet(client, requestURL, apiKey)
	if err != nil {
		return err
	}
	if status != http.StatusOK {
		return fmt.Errorf("GET %s returned %d", requestURL, status)
	}
	if !strings.Contains(body, expected) {
		return fmt.Errorf("GET %s did not return %s", requestURL, expected)
	}
	return nil
}

// preflightGet performs one plain GET and returns its status and body.
func preflightGet(client *http.Client, requestURL, apiKey string) (int, string, error) {
	request, err := http.NewRequest(http.MethodGet, requestURL, nil)
	if err != nil {
		return 0, "", err
	}
	if apiKey != "" {
		request.Header.Set("x-api-key", apiKey)
	}

	response, err := client.Do(request)
	if err != nil {
		return 0, "", err
	}
	defer func() { _ = response.Body.Close() }()

	body, err := io.ReadAll(response.Body)
	if err != nil {
		return response.StatusCode, "", err
	}

	return response.StatusCode, string(body), nil
}

