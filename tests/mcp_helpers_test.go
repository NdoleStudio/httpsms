// requestJSONAs is requestJSON for an arbitrary API key: it retries a 401 for
// a short while, because a freshly minted phone API key is not immediately
// visible to every API instance's cache.
func requestJSONAs(
	ctx context.Context,
	t *testing.T,
	method string,
	path string,
	apiKey string,
	payload any,
	expectedStatus int,
	output any,
) {
	t.Helper()

	var encoded []byte
	if payload != nil {
		var err error
		encoded, err = json.Marshal(payload)
		require.NoError(t, err)
	}

	deadline := time.Now().Add(20 * time.Second)
	for {
		request, err := http.NewRequestWithContext(ctx, method, apiBaseURL+path, strings.NewReader(string(encoded)))
		require.NoError(t, err)
		request.Header.Set("x-api-key", apiKey)
		request.Header.Set("Content-Type", "application/json")

		response, err := http.DefaultClient.Do(request)
		require.NoError(t, err)

		body, err := io.ReadAll(response.Body)
		_ = response.Body.Close()
		require.NoError(t, err)

		if response.StatusCode == http.StatusUnauthorized && expectedStatus != http.StatusUnauthorized && time.Now().Before(deadline) {
			time.Sleep(500 * time.Millisecond)
			continue
		}

		require.Equal(t, expectedStatus, response.StatusCode, "%s %s: %s", method, path, string(body))
		if output != nil {
			require.NoError(t, json.Unmarshal(body, output))
		}
		return
	}
}

