// bootstrapPrimaryAPIKey rotates userID's primary httpSMS API key through a
// delegation token this test binary mints itself, and returns the brand-new
// key.
//
// It is how a test that must start from a primary API key whose value it knows
// obtains one, instead of assuming a seeded key is still current: a seeded
// primary key is only ever valid until the first run of the first test that
// rotates it, which is exactly what made this suite non-re-runnable. The
// delegation token is bound to this one method and path, so the API's own
// delegated-MCP verifier accepts it for nothing else.
func bootstrapPrimaryAPIKey(t *testing.T, userID string) string {
	t.Helper()

	path := "/v1/users/" + url.PathEscape(userID) + "/api-keys"
	token := signAPIDelegationToken(t, userID, []string{"user-api-key:rotate"}, http.MethodDelete, path)

	status, body := apiRequestWithBearer(t, http.MethodDelete, path, token)
	require.Equal(t, http.StatusOK, status, "cannot bootstrap a primary API key for %s: %s", userID, redactSecrets(body))

	var rotated struct {
		Data struct {
			ID     string `json:"id"`
			APIKey string `json:"api_key"`
		} `json:"data"`
	}
	require.NoError(t, json.Unmarshal([]byte(body), &rotated))
	require.Equal(t, userID, rotated.Data.ID)
	require.NotEmpty(t, rotated.Data.APIKey)

	return rotated.Data.APIKey
}

// currentRateLimitWindow returns the start of the UTC hour the MCP service's
// rate limiter is currently counting hourly budgets in. It mirrors
// time.Now().UTC().Truncate(time.Hour) in mcp/internal/server/rate_limit.go.
func currentRateLimitWindow() time.Time {
	return time.Now().UTC().Truncate(time.Hour)
}

// waitForRateLimitWindowHeadroom blocks until the current hourly rate-limit
// window has enough time left for a whole exhaust-the-budget sequence.
//
// The hourly budget is counted in fixed UTC hour windows, so a sequence that
// straddles the top of the hour would see the counter reset midway and the
// final call succeed. Waiting out the last seconds of a window keeps the
// assertion exactly as strict (the call after the budget really must be
// refused) instead of weakening it to tolerate a reset.
func waitForRateLimitWindowHeadroom(t *testing.T) {
	t.Helper()

	const headroom = 30 * time.Second

	remaining := time.Until(currentRateLimitWindow().Add(time.Hour))
	if remaining >= headroom {
		return
	}

	t.Logf("only %s left in the current UTC rate-limit window; waiting for the next one", remaining.Round(time.Second))
	time.Sleep(remaining + time.Second)
}
